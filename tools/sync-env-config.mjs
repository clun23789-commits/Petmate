import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, "..");
const require = createRequire(import.meta.url);

const {
  DEFAULT_APP_ENV,
  ENV_PROFILE_BY_ENV
} = require(path.join(projectRoot, "miniprogram", "config", "env.profiles.js"));

const generatedPath = path.join(projectRoot, "miniprogram", "config", "env.generated.js");
const supportedEnvNames = Object.keys(ENV_PROFILE_BY_ENV);

function parseArgs(argv) {
  return argv.slice(2).reduce((acc, item) => {
    if (!item.startsWith("--")) {
      return acc;
    }

    const [key, ...rest] = item.slice(2).split("=");
    acc[key] = rest.length ? rest.join("=") : "true";
    return acc;
  }, {});
}

function normalizeString(value) {
  return typeof value === "string" ? value.trim() : "";
}

function normalizeBoolean(value) {
  if (value === true || value === "true") {
    return true;
  }

  if (value === false || value === "false") {
    return false;
  }

  return null;
}

function isPlaceholder(value) {
  const text = normalizeString(value).toLowerCase();
  return !text ||
    text.includes("__") ||
    text.includes("placeholder") ||
    text.includes("replace") ||
    text.includes("demo") ||
    text.includes("test");
}

function fail(message) {
  console.error("Failed to sync Petmate environment config:");
  console.error(`- ${message}`);
  console.error(`- Supported env values: ${supportedEnvNames.join(", ")}`);
  process.exit(1);
}

function formatObjectLiteral(object, indentLevel) {
  const entries = Object.entries(object);
  if (entries.length === 0) {
    return "{}";
  }

  const indent = " ".repeat(indentLevel);
  const innerIndent = " ".repeat(indentLevel + 2);
  const lines = entries.map(([key, value]) => {
    return `${innerIndent}${key}: ${JSON.stringify(value)}`;
  });

  return `{\n${lines.join(",\n")}\n${indent}}`;
}

const args = parseArgs(process.argv);
const selectedEnv = normalizeString(args.env || process.env.PETMATE_APP_ENV || DEFAULT_APP_ENV);
const cloudEnvId = normalizeString(args.cloudEnvId || process.env.PETMATE_CLOUD_ENV_ID);
const traceUser = normalizeBoolean(args.traceUser);

if (!supportedEnvNames.includes(selectedEnv)) {
  fail(`Unknown env: ${selectedEnv || "(empty)"}`);
}

const profile = ENV_PROFILE_BY_ENV[selectedEnv];
const overrides = {};

if (cloudEnvId) {
  overrides.cloudEnvId = cloudEnvId;
}

if (traceUser !== null) {
  overrides.traceUser = traceUser;
}

if (selectedEnv === "production") {
  if (!cloudEnvId) {
    fail("production requires an explicit cloudEnvId via --cloudEnvId or PETMATE_CLOUD_ENV_ID.");
  }

  if (isPlaceholder(cloudEnvId)) {
    fail("production cloudEnvId is missing or looks like a placeholder/demo/test value.");
  }
}

const finalCloudEnvId = overrides.cloudEnvId || profile.cloudEnvId;
if (!finalCloudEnvId) {
  fail(`cloudEnvId is empty for env: ${selectedEnv}`);
}

const content = `"use strict";

// This file is generated by tools/sync-env-config.mjs. Do not edit manually.

module.exports = {
  SELECTED_APP_ENV: ${JSON.stringify(selectedEnv)},
  ENV_OVERRIDES: ${formatObjectLiteral(overrides, 2)}
};
`;

fs.writeFileSync(generatedPath, content, "utf8");

console.log(`Synced Petmate environment config: ${selectedEnv}`);
console.log(`Wrote ${path.relative(projectRoot, generatedPath).replace(/\\/g, "/")}`);
